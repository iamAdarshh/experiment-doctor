// `npm run real-world`: runs the doctor on the real-world projects in tests/real-world and writes REPORT.md.
//   npm run real-world             projects whose files are in the repo (permissive licences)
//   npm run real-world -- --fetch  also downloads the other projects (no or copyleft licence) at their recorded
//                                  commit into tests/real-world/.cache (git-ignored), then runs on all of them
// See tests/real-world/README.md for how the projects were collected.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { runChecks } from '../lib/doctor';
import { ENGINE_VERSION } from '../lib/doctor/version';
import { readWorkspace } from './workspace';

type Source = {
  id: string;
  group: string;
  repo: string;
  commit: string;
  license: string;
  files: string[];
  package: string | null;
  included: boolean;
};

const ROOT = resolve(__dirname, '..', 'tests', 'real-world');
const sources = (JSON.parse(readFileSync(join(ROOT, 'sources.json'), 'utf8')) as { projects: Source[] }).projects;
const fetchMissing = process.argv.includes('--fetch');

function folderOf(source: Source): string {
  return join(ROOT, source.included ? 'projects' : '.cache', source.id);
}

/** Downloads one manifest-only project's files at the recorded commit (public raw GitHub URLs). */
async function download(source: Source): Promise<void> {
  const folder = folderOf(source);
  const wanted = [...source.files.map((file) => ({ from: file, to: file })), ...(source.package ? [{ from: source.package, to: 'package.json' }] : [])];
  for (const { from, to } of wanted) {
    const target = join(folder, to);
    if (existsSync(target)) continue;
    const response = await fetch(`https://raw.githubusercontent.com/${source.repo}/${source.commit}/${from}`);
    if (!response.ok) throw new Error(`${source.id}: ${from} -> HTTP ${response.status}`);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, await response.text());
  }
}

type Row = { source: Source; status: string; issues: string[] };

async function main() {
  if (fetchMissing) {
    for (const source of sources.filter((item) => !item.included)) {
      try {
        await download(source);
      } catch (error) {
        console.warn(`skip ${(error as Error).message}`);
      }
    }
  }

  const rows: Row[] = [];
  for (const source of sources) {
    // Without --fetch, only the projects stored in the repo, so REPORT.md is the same on every machine.
    if (!source.included && !fetchMissing) continue;
    const folder = folderOf(source);
    if (!existsSync(folder)) continue;
    const workspace = readWorkspace(folder);
    const result = runChecks(workspace.input);
    const issues = result.issues.map((issue) => `${issue.confidence} ${issue.ruleId} (${workspace.locate(issue) ?? issue.source})`);
    let status: string;
    if (result.parseErrors.length > 0) status = 'parse error';
    else if (result.issues.some((issue) => issue.confidence === 'certain')) status = 'certain';
    else if (result.issues.length > 0) status = 'possible only';
    else if (result.notChecked.some((item) => item.ruleId === 'events-disabled')) status = 'nothing checked';
    else status = 'clean';
    rows.push({ source, status, issues });
  }

  const groups = [...new Set(rows.map((row) => row.source.group))];
  const statuses = ['certain', 'possible only', 'clean', 'nothing checked', 'parse error'];
  const lines: string[] = [
    '# Real-world run',
    '',
    `Engine \`${ENGINE_VERSION}\`. ${rows.length} of ${sources.length} projects ran${fetchMissing ? '' : ' (run with `--fetch` to include the manifest-only ones)'}.`,
    'Generated by `npm run real-world`; do not edit by hand.',
    '',
    `| Group | Projects | ${statuses.join(' | ')} |`,
    `| --- | --- | ${statuses.map(() => '---').join(' | ')} |`,
    ...groups.map((group) => {
      const inGroup = rows.filter((row) => row.source.group === group);
      return `| ${group} | ${inGroup.length} | ${statuses.map((status) => inGroup.filter((row) => row.status === status).length).join(' | ')} |`;
    }),
    '',
  ];
  for (const group of groups) {
    lines.push(`## ${group}`, '', '| Project | Result | Issues |', '| --- | --- | --- |');
    for (const row of rows.filter((item) => item.source.group === group)) {
      const name = `[${row.source.repo}](https://github.com/${row.source.repo}/tree/${row.source.commit})${row.source.included ? '' : ' (fetched)'}`;
      lines.push(`| ${name} | ${row.status} | ${row.issues.join('<br>') || ''} |`);
    }
    lines.push('');
  }
  writeFileSync(join(ROOT, 'REPORT.md'), lines.join('\n'));
  console.log(lines.slice(0, 6 + groups.length + 3).join('\n'));
}

void main();
