/**
 * Deterministic code changes for the demo app (apps/demo-pricing).
 *
 * No LLM writes code. The experiment PR and the cleanup PR are generated from templates and the
 * validated plan, and only touch the region between the `flagpilot:cta` markers in page.tsx.
 * Output is a map of { path: newContent | null (delete) } that github.ts commits to a branch.
 */
import type { ExperimentPlan } from './plan.js';

export const APP_DIR = 'apps/demo-pricing';
export const PAGE = `${APP_DIR}/app/page.tsx`;
export const CTA_COMPONENT = `${APP_DIR}/components/PricingCTA.tsx`;

const REGION = /(\{\/\* flagpilot:cta:start \*\/\}\n)([\s\S]*?)(\n\s*\{\/\* flagpilot:cta:end \*\/\})/;
const IMPORT_LINE = "import { PricingCTA } from '../components/PricingCTA';";

export type FileChanges = Record<string, string | null>;

export class CodemodError extends Error {}

function replaceRegion(page: string, replacement: string): string {
  const m = page.match(REGION);
  if (!m) throw new CodemodError(`${PAGE} has no flagpilot:cta markers; can't apply the codemod safely.`);
  const indent = m[2]!.match(/^\s*/)![0];
  return page.replace(REGION, `$1${indent}${replacement}$3`);
}

/** JS string literal, safe for any label text. */
const lit = (s: string) => JSON.stringify(s);

export function ctaComponent(plan: ExperimentPlan): string {
  const arms = [plan.control, ...plan.variants];
  return `'use client';
/**
 * Main pricing CTA, driven by the Flagsmith experiment \`${plan.flagName}\`.
 * Generated by FlagPilot from the approved plan. Removed again by the cleanup PR.
 */
import { useExperiment, useFlagsmith, useFlagsmithLoading } from '@flagsmith/flagsmith/react';

export const FLAG = ${lit(plan.flagName)};
/** Must match the Flagsmith metric's event name EXACTLY (case-sensitive). */
export const EVENT = ${lit(plan.metric.event)};

/** Flag value (variant key) -> button text. */
const LABELS: Record<string, string> = {
${arms.map((a) => `  ${a.key}: ${lit(a.label)},`).join('\n')}
};

export function PricingCTA() {
  // useExperiment records the exposure for enrolled users; null until flags have loaded.
  const flag = useExperiment(FLAG);
  const loading = useFlagsmithLoading();
  const flagsmith = useFlagsmith();

  if (!flag && loading?.isLoading !== false) return <span className="cta-skeleton" aria-hidden />;

  // Unknown value or flag missing (e.g. Flagsmith unreachable): fall back to control.
  const variant = String(flag?.value ?? 'control');
  const label = LABELS[variant] ?? LABELS.control;

  return (
    <a
      className="cta"
      href="#signup"
      data-variant={variant}
      onClick={() => {
        flagsmith.trackEvent(EVENT); // conversion, joined to the exposure via the identity
        void flagsmith.flushEvents(); // don't wait for the ~10s batch
      }}
    >
      {label}
    </a>
  );
}
`;
}

/** Experiment PR: add the component and render it in place of the static button. */
export function experimentChanges(plan: ExperimentPlan, currentPage: string): FileChanges {
  let page = replaceRegion(currentPage, '<PricingCTA />');
  if (!page.includes(IMPORT_LINE)) page = `${IMPORT_LINE}\n${page}`;
  return { [PAGE]: page, [CTA_COMPONENT]: ctaComponent(plan) };
}

/** Cleanup PR: hard-code the winner, delete the experiment component, drop the import. */
export function cleanupChanges(plan: ExperimentPlan, winnerKey: string, currentPage: string): FileChanges {
  const winner = [plan.control, ...plan.variants].find((a) => a.key === winnerKey);
  if (!winner) throw new CodemodError(`Unknown winner "${winnerKey}"`);
  const escaped = winner.label.replace(/[{}<>]/g, (c) => `{'${c}'}`); // JSX-safe text
  let page = replaceRegion(currentPage, `<a className="cta" href="#signup">${escaped}</a>`);
  page = page.replace(`${IMPORT_LINE}\n`, '');
  return { [PAGE]: page, [CTA_COMPONENT]: null };
}
